/**
 * The test-cycle closure report — built here, used three ways:
 *
 *   npm run report:cycle     by hand, for everything or a chosen scope   (scripts/cycle-report.ts)
 *   after every test run     automatically, for the stories that ran     (lib/cycleReporter.ts)
 *   npm run regression       for the release and tickets you selected    (scripts/regression.ts)
 *
 * It assembles what the harness already produces into one summary: every planned test case in scope and how
 * it ended, pass rates by priority, acceptance-criteria coverage per story, open defects, traceability gaps,
 * and an evaluation of the exit criteria in PROJECT-PROFILE.md section 10.
 *
 * Inputs, all optional — the report says plainly which were missing:
 *   specs/<STORY-KEY>.plan.md              planned test cases, AC → TCID links, release and epic
 *   specs/execution/automated-results.csv  every test case's latest automated result, across runs
 *   test-results/results.json              the latest run — folded into the file above as each run ends
 *   specs/execution/manual-results.csv     manual executions
 *   specs/defects/log/<entry id>.json      defects and their lifecycle status, one file each
 *
 * The automated record matters because a cycle is many runs, not one: the regression, then the healer's
 * re-runs of what failed, then a retest. The latest result of each test case is what the cycle reports.
 *
 * Releases here are the project's own — the client release a story ships in. The harness's version never
 * appears in a report.
 */

import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { projectProfile } from '../../config/projectProfile';
import { DEFECT_DIR, readDefects } from './defects';
import { NO_RELEASE, parsePlan, Plan, PlannedCase, planFiles, releaseOfSpec, ROOT, storyKeyOf, storySpecFiles, TCID_PREFIX } from './trace';

export type Outcome = 'Passed' | 'Failed' | 'Flaky' | 'Blocked' | 'Skipped' | 'Not Run';

export interface CycleScope {
    /** Only these stories. */
    stories?: string[];
    /** Only stories in these client releases. */
    releases?: string[];
    /** Shown in the report's title and filename, e.g. "release 2.26". Derived from the scope if omitted. */
    label?: string;
    /** Where the results came from, for the report's header — e.g. "automatic, after the run". */
    trigger?: string;
    /** Ignore results executed before this date (`YYYY-MM-DD`) — they count as not run. For a new cycle. */
    since?: string;
    /** Write to specs/execution/closure/, which is committed, instead of reports/. For the cycle's final report. */
    closure?: boolean;
    /** Only stories in these epics. */
    epics?: string[];
    /** A formal report: the QA-Report_… name, a sign-off block, written to the committed specs/execution/reports/. */
    formal?: boolean;
    /** Who the report is generated by, when QA_TESTER_NAME and the git user name are both missing — or to override them. */
    by?: string;
    /** Ticket details from Jira, fetched by the reporter agent — titles, statuses, the scope's tickets with no plan. */
    jira?: JiraData;
    /** A short written summary from the reporter agent, shown under "Notes". Never a source of numbers. */
    notes?: string;
    /** Compute everything and return it, but write nothing — so the agent can read the numbers before its notes. */
    preview?: boolean;
}

/** Ticket details the reporter agent fetched from Jira, passed in as a JSON file. */
export interface JiraData {
    /** Per story key: its Jira title and status. */
    tickets?: Record<string, { title?: string; status?: string }>;
    /** Every ticket Jira lists for the scope — e.g. a release's fix version — so ones with no plan show up. */
    scopeTickets?: { key: string; title?: string; status?: string }[];
}

/** Who a report is generated by, and where the name came from. */
export function generatedBy(given?: string): { name: string; source: string } {
    if (given?.trim()) return { name: given.trim(), source: 'given' };
    const fromEnv = process.env.QA_TESTER_NAME?.trim();
    if (fromEnv) return { name: fromEnv, source: 'QA_TESTER_NAME' };
    try {
        const fromGit = execFileSync('git', ['config', 'user.name'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
        if (fromGit) return { name: fromGit, source: 'git user.name' };
    } catch { /* no git */ }
    return { name: '', source: 'not recorded' };
}

/** The harness version this copy started from (PROJECT-PROFILE.md section 1), else the template's CHANGELOG. */
export function harnessVersion(): string {
    const fromProfile = has('PROJECT-PROFILE.md')
        ? read('PROJECT-PROFILE.md').match(/\| Harness version this copy started from \| `([^`<]+)`/)?.[1]
        : undefined;
    if (fromProfile) return fromProfile;
    return (has('CHANGELOG.md') ? read('CHANGELOG.md').match(/^## (\d+\.\d+\.\d+)\b/m)?.[1] : undefined) ?? '—';
}

/** The headline numbers, returned with every report — and alone, in preview. */
export interface CycleMetrics {
    label: string;
    stories: string[];
    total: number;
    outcomes: Record<Outcome, { automated: number; manual: number }>;
    byPriority: { priority: string; total: number; passing: number; rate: string }[];
    acceptanceCriteria: { passing: number; total: number };
    openDefects: { id: string; severity: string; tcid: string; trackerKey: string; summary: string }[];
    criteria: { name: string; threshold: string; actual: string; met: boolean }[];
    allMet: boolean;
    generatedBy: { name: string; source: string };
    perStory: { key: string; title: string; status: string; passing: number; total: number; failed: number; blocked: number; notRun: number }[];
    noPlan: string[];
    notInRelease: string[];
}

export const AUTOMATED_RECORD = 'specs/execution/automated-results.csv';
export const MANUAL_RECORD = 'specs/execution/manual-results.csv';
const LATEST_RUN = 'test-results/results.json';

export interface CycleResult {
    file: string | null;
    /** The report's title — also the HTML page title. */
    title?: string;
    cases: number;
    allMet: boolean;
    failingCriteria: string[];
    summary: string;
    metrics?: CycleMetrics;
}

const read = (p: string) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const has = (p: string) => fs.existsSync(path.join(ROOT, p));
const pct = (n: number, d: number) => (d === 0 ? 100 : Math.round((n / d) * 1000) / 10);

/** Every plan, with its release resolved — the plan's `**Release:**`, else the folder its spec lives in. */
export function plansWithRelease(): Plan[] {
    const specRelease = new Map<string, string>();
    for (const f of storySpecFiles()) {
        const release = releaseOfSpec(f);
        if (release) specRelease.set(storyKeyOf(f, '.spec.ts'), release);
    }
    return planFiles()
        .map(parsePlan)
        .map((p) => ({ ...p, release: p.release ?? specRelease.get(p.storyKey) ?? null }));
}

function scopeLabel(scope: CycleScope, plans: Plan[]): string {
    if (scope.label) return scope.label;
    if (scope.releases?.length) return scope.releases.map((r) => (r === NO_RELEASE ? 'no release' : `release ${r}`)).join(', ');
    if (scope.epics?.length) return scope.epics.map((e) => `epic ${e}`).join(', ');
    if (scope.stories?.length) return plans.length === 1 ? plans[0].storyKey : `${plans.length} stories`;
    return 'all stories';
}

/** The scope part of a formal report's name: `release-2.26`, `epic-FK-100`, `FK-1304`, `3-stories`. */
function scopeNamePart(scope: CycleScope, plans: Plan[]): string {
    if (scope.releases?.length) return scope.releases.map((r) => (r === NO_RELEASE ? 'no-release' : `release-${r}`)).join('+');
    if (scope.epics?.length) return scope.epics.map((e) => `epic-${e}`).join('+');
    // Several stories: their keys in order, so two different sets never share a name.
    if (scope.stories?.length) return plans.map((p) => p.storyKey).sort().join('+');
    return 'all-stories';
}

/** Letters, digits, dots and dashes only — keeps a story key's case, unlike slug(). */
const namePart = (s: string) => s.replace(/[^A-Za-z0-9.-]+/g, '-').replace(/^-+|-+$/g, '') || 'x';

/** A table cell: no line breaks, and pipes escaped so they cannot split the cell. */
const cell = (v: string | number) => String(v).replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9.]+/g, '-').replace(/^-+|-+$/g, '');

// ---------------------------------------------------------------- automated results

export interface PwAttachment { name: string; contentType: string; path?: string }
export interface PwResult { status: string; attachments?: PwAttachment[] }
export interface PwTest { status: 'expected' | 'unexpected' | 'flaky' | 'skipped'; projectName?: string; annotations?: { type: string }[]; results?: PwResult[] }
export interface PwSpec { title: string; file: string; tests: PwTest[] }
export interface PwSuite { specs?: PwSpec[]; suites?: PwSuite[] }
export interface PwReport { suites?: PwSuite[]; stats?: { startTime?: string; duration?: number } }

/** Every spec in Playwright's JSON report, flattened. */
export function eachSpec(report: PwReport): PwSpec[] {
    const out: PwSpec[] = [];
    const walk = (suites: PwSuite[] = []) => {
        for (const s of suites) {
            out.push(...(s.specs ?? []));
            walk(s.suites);
        }
    };
    walk(report.suites);
    return out;
}

function specOutcome(spec: PwSpec): Outcome {
    const statuses = spec.tests.map((t) => t.status);
    if (statuses.includes('unexpected')) return 'Failed';
    if (statuses.every((s) => s === 'skipped')) {
        const fixme = spec.tests.some((t) => t.annotations?.some((a) => a.type === 'fixme'));
        return fixme ? 'Blocked' : 'Skipped';
    }
    if (statuses.includes('flaky')) return 'Flaky';
    return 'Passed';
}

const RANK: Outcome[] = ['Failed', 'Blocked', 'Flaky', 'Skipped', 'Passed', 'Not Run'];
const worse = (a: Outcome, b: Outcome) => (RANK.indexOf(a) <= RANK.indexOf(b) ? a : b);

/** TCID → outcome, from Playwright's JSON report. Also the count of results with no TCID. */
export function readAutomatedResults(file = LATEST_RUN): {
    outcomes: Map<string, Outcome>;
    specs: Map<string, { file: string; browsers: string[] }>;
    untraced: number;
    started?: string;
    found: boolean;
} {
    const outcomes = new Map<string, Outcome>();
    const specs = new Map<string, { file: string; browsers: string[] }>();
    if (!has(file)) return { outcomes, specs, untraced: 0, found: false };
    let untraced = 0;
    const report = JSON.parse(read(file)) as PwReport;
    for (const spec of eachSpec(report)) {
        const tcid = spec.title.match(TCID_PREFIX)?.[1];
        if (!tcid) { untraced++; continue; }
        const o = specOutcome(spec);
        outcomes.set(tcid, outcomes.has(tcid) ? worse(outcomes.get(tcid)!, o) : o);
        const browsers = [...new Set([...(specs.get(tcid)?.browsers ?? []), ...spec.tests.map((t) => t.projectName ?? '').filter(Boolean)])];
        specs.set(tcid, { file: `tests/${spec.file}`.replace(/^tests\/tests\//, 'tests/'), browsers });
    }
    return { outcomes, specs, untraced, started: report.stats?.startTime, found: true };
}

// ---------------------------------------------------------------- the automated record

interface RecordRow { tcid: string; status: Outcome; executedOn: string; browser: string; build: string; spec: string }
export const RECORD_HEADER = ['TCID', 'Status', 'Executed On', 'Browser', 'Build', 'Spec'];

/**
 * One row per TCID. A record can hold two rows for one test case after two branches each updated it and git
 * kept both lines (the results CSVs merge with `merge=union`, see .gitattributes): the newest `Executed On`
 * wins, a later line breaking a tie. A seeded manual row has no date, so any executed row beats it.
 */
export function readRecord(file: string, header: string[]): Map<string, Record<string, string>> {
    const rows = new Map<string, Record<string, string>>();
    if (!has(file)) return rows;
    const [head, ...body] = parseCsv(read(file));
    if (!head) return rows;
    const cols = head.map((h) => h.trim());
    for (const r of body) {
        const row: Record<string, string> = {};
        header.forEach((h) => { row[h] = (r[cols.indexOf(h)] ?? '').trim(); });
        if (!row.TCID || row.TCID === 'TCID') continue;
        const kept = rows.get(row.TCID);
        if (!kept || (row['Executed On'] ?? '') >= (kept['Executed On'] ?? '')) rows.set(row.TCID, row);
    }
    return rows;
}

const csvCell = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

/**
 * Folds the latest run into specs/execution/automated-results.csv: each test case that ran gets its new
 * result, every other row is kept. Called as each run ends, by lib/cycleReporter.ts.
 */
export function recordAutomatedResults(): { recorded: number; file: string } {
    const latest = readAutomatedResults();
    if (!latest.found || latest.outcomes.size === 0) return { recorded: 0, file: AUTOMATED_RECORD };
    const rows = readRecord(AUTOMATED_RECORD, RECORD_HEADER);
    const executedOn = (latest.started ? new Date(latest.started) : new Date()).toISOString().slice(0, 16).replace('T', ' ');
    const build = process.env.BUILD_UNDER_TEST?.trim() ?? '';
    for (const [tcid, status] of latest.outcomes) {
        const spec = latest.specs.get(tcid);
        const row: RecordRow = { tcid, status, executedOn, browser: spec?.browsers.join(' ') ?? '', build, spec: spec?.file ?? '' };
        rows.set(tcid, { TCID: row.tcid, Status: row.status, 'Executed On': row.executedOn, Browser: row.browser, Build: row.build, Spec: row.spec });
    }
    const sorted = [...rows.values()].sort((a, b) => a.TCID.localeCompare(b.TCID, undefined, { numeric: true }));
    const text = [RECORD_HEADER.join(','), ...sorted.map((r) => RECORD_HEADER.map((h) => csvCell(r[h] ?? '')).join(','))].join('\n') + '\n';
    fs.mkdirSync(path.dirname(path.join(ROOT, AUTOMATED_RECORD)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, AUTOMATED_RECORD), text, 'utf8');
    return { recorded: latest.outcomes.size, file: AUTOMATED_RECORD };
}

// ---------------------------------------------------------------- manual results

function parseCsv(text: string): string[][] {
    const rows: string[][] = [];
    let row: string[] = [], cell = '', quoted = false;
    for (let i = 0; i < text.length; i++) {
        const ch = text[i];
        if (quoted) {
            if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
            else if (ch === '"') quoted = false;
            else cell += ch;
        } else if (ch === '"') quoted = true;
        else if (ch === ',') { row.push(cell); cell = ''; }
        else if (ch === '\n' || ch === '\r') {
            if (ch === '\r' && text[i + 1] === '\n') i++;
            row.push(cell); rows.push(row); row = []; cell = '';
        } else cell += ch;
    }
    if (cell || row.length) { row.push(cell); rows.push(row); }
    return rows.filter((r) => r.some((c) => c.trim()));
}

// ---------------------------------------------------------------- the report

export function buildCycleReport(scope: CycleScope = {}): CycleResult {
    const inputs: string[] = [];

    // ---- scope
    let plans = plansWithRelease();
    if (scope.releases?.length) plans = plans.filter((p) => scope.releases!.includes(p.release ?? NO_RELEASE));
    if (scope.epics?.length) plans = plans.filter((p) => !!p.epic && scope.epics!.includes(p.epic));
    if (scope.stories?.length) plans = plans.filter((p) => scope.stories!.includes(p.storyKey));
    const inScope = new Set(plans.map((p) => p.storyKey));
    const label = scopeLabel(scope, plans);

    if (plans.length === 0) {
        return { file: null, cases: 0, allMet: true, failingCriteria: [], summary: `no plans in scope (${label}) — nothing to report` };
    }

    const cases = plans.flatMap((p) => p.cases).filter((c) => !c.retired);
    const retiredCount = plans.flatMap((p) => p.cases).filter((c) => c.retired).length;

    // ---- automated: the record across runs, else the latest run alone
    const storyOf = (id: string) => id.replace(/-TC\d{3}$/, '');
    const fresh = (on: string) => !scope.since || on.slice(0, 10) >= scope.since;
    const auto = readAutomatedResults();
    const automated = new Map<string, Outcome>();
    const executedOn: string[] = [];
    const builds = new Set<string>();
    const browsers = new Set<string>();
    if (has(AUTOMATED_RECORD)) {
        inputs.push(AUTOMATED_RECORD);
        for (const [id, row] of readRecord(AUTOMATED_RECORD, RECORD_HEADER)) {
            if (!inScope.has(storyOf(id)) || !fresh(row['Executed On'])) continue;
            automated.set(id, row.Status as Outcome);
            executedOn.push(row['Executed On']);
            if (row.Build) builds.add(row.Build);
            for (const b of (row.Browser ?? '').split(/\s+/)) if (b) browsers.add(b);
        }
    } else if (auto.found) {
        inputs.push(LATEST_RUN);
        for (const [id, o] of auto.outcomes) if (inScope.has(storyOf(id))) automated.set(id, o);
    }
    executedOn.sort();

    // ---- manual
    const manual = new Map<string, Outcome>();
    if (has(MANUAL_RECORD)) {
        inputs.push(MANUAL_RECORD);
        for (const [id, row] of readRecord(MANUAL_RECORD, ['TCID', 'Status', 'Executed On'])) {
            const s = row.Status;
            const o: Outcome = s === 'Passed' ? 'Passed' : s === 'Failed' ? 'Failed' : s === 'Blocked' ? 'Blocked' : 'Not Run';
            manual.set(id, o === 'Not Run' || fresh(row['Executed On']) ? o : 'Not Run');
        }
    }

    // ---- defects, in scope
    const defectLog = readDefects();
    if (defectLog.files.length) inputs.push(DEFECT_DIR);
    const defects = defectLog.entries.filter((d) => !d.storyKey || inScope.has(d.storyKey));
    const openDefects = defects.filter((d) => d.status === 'pending' || d.status === 'raised');

    // ---- per-case outcome
    const outcomeOf = (c: PlannedCase): Outcome =>
        c.testType === 'Manual' ? manual.get(c.tcid) ?? 'Not Run' : automated.get(c.tcid) ?? 'Not Run';
    const isPass = (o: Outcome) => o === 'Passed' || o === 'Flaky';
    const outcomes = new Map(cases.map((c) => [c.tcid, outcomeOf(c)]));
    const count = (o: Outcome) => [...outcomes.values()].filter((x) => x === o).length;

    // ---- metrics
    const byPriority = ([1, 2, 3] as const).map((p) => {
        const inP = cases.filter((c) => c.priority === p);
        const passed = inP.filter((c) => isPass(outcomes.get(c.tcid)!)).length;
        return { p, total: inP.length, passed, rate: pct(passed, inP.length) };
    });

    type AcState = 'Passing' | 'Failing' | 'Blocked by defect' | 'Not executed' | 'Not covered';
    const acRows: { story: string; ac: string; ids: string[]; state: AcState }[] = [];
    for (const plan of plans) {
        for (const [ac, ids] of plan.acceptanceCriteria) {
            const live = ids.filter((id) => outcomes.has(id));
            const results = live.map((id) => outcomes.get(id)!);
            const state: AcState =
                // An AC passes only when every test case that verifies it passes: one failing or
                // defect-blocked case means the app does not yet meet that criterion.
                live.length === 0 ? 'Not covered'
                : results.includes('Failed') ? 'Failing'
                : results.includes('Blocked') ? 'Blocked by defect'
                : results.every(isPass) ? 'Passing'
                : 'Not executed';
            acRows.push({ story: plan.storyKey, ac, ids, state });
        }
    }
    const acPassing = acRows.filter((r) => r.state === 'Passing').length;
    const notExecuted = count('Not Run');

    const plannedIds = new Set(plans.flatMap((p) => p.cases.map((c) => c.tcid)));
    const orphanResults = [...automated.keys()].filter((id) => !plannedIds.has(id));

    // ---- exit criteria
    const ec = projectProfile.exitCriteria;
    const criteria: { name: string; threshold: string; actual: string; met: boolean }[] = [];
    const p1 = byPriority[0], p2 = byPriority[1];
    criteria.push({ name: 'Priority 1 test cases passing', threshold: `${ec.priority1PassRate}%`, actual: p1.total ? `${p1.rate}% (${p1.passed}/${p1.total})` : 'no P1 cases', met: p1.rate >= ec.priority1PassRate });
    criteria.push({ name: 'Priority 2 test cases passing', threshold: `${ec.priority2PassRate}%`, actual: p2.total ? `${p2.rate}% (${p2.passed}/${p2.total})` : 'no P2 cases', met: p2.rate >= ec.priority2PassRate });
    const acRate = pct(acPassing, acRows.length);
    criteria.push({ name: 'Acceptance criteria with every test case passing', threshold: `${ec.acceptanceCriteriaCoverage}%`, actual: `${acRate}% (${acPassing}/${acRows.length})`, met: acRate >= ec.acceptanceCriteriaCoverage });
    for (const [sev, max] of Object.entries(ec.maxOpenDefects)) {
        const n = openDefects.filter((d) => d.severity === sev).length;
        criteria.push({ name: `Open defects at ${sev}`, threshold: `≤ ${max}`, actual: String(n), met: n <= (max ?? Infinity) });
    }
    criteria.push({ name: 'Test cases not executed', threshold: `≤ ${ec.maxNotExecuted}`, actual: String(notExecuted), met: notExecuted <= ec.maxNotExecuted });
    const allMet = criteria.every((c) => c.met);

    // ---- per story, Jira, and stories not yet in a release
    const jira = scope.jira ?? {};
    const perStory = plans.map((p) => {
        const live = p.cases.filter((c) => !c.retired);
        const of = (o: Outcome) => live.filter((c) => outcomes.get(c.tcid) === o).length;
        const acs = acRows.filter((r) => r.story === p.storyKey);
        return {
            key: p.storyKey,
            title: jira.tickets?.[p.storyKey]?.title ?? p.title ?? '—',
            status: jira.tickets?.[p.storyKey]?.status ?? '—',
            release: p.release ?? '—',
            epic: p.epic ?? '—',
            passing: live.filter((c) => isPass(outcomes.get(c.tcid)!)).length,
            total: live.length,
            failed: of('Failed'),
            blocked: of('Blocked'),
            notRun: of('Not Run'),
            ac: `${acs.filter((r) => r.state === 'Passing').length}/${acs.length}`,
        };
    });
    const planned = new Set(plansWithRelease().map((p) => p.storyKey));
    const noPlan = (jira.scopeTickets ?? []).filter((t) => !planned.has(t.key));
    const notInRelease = plans.filter((p) => !p.release).map((p) => p.storyKey);

    const by = generatedBy(scope.by);
    const metrics: CycleMetrics = {
        label,
        stories: plans.map((p) => p.storyKey),
        total: cases.length,
        outcomes: Object.fromEntries((['Passed', 'Flaky', 'Failed', 'Blocked', 'Skipped', 'Not Run'] as Outcome[]).map((o) => [o, {
            automated: cases.filter((c) => c.testType !== 'Manual' && outcomes.get(c.tcid) === o).length,
            manual: cases.filter((c) => c.testType === 'Manual' && outcomes.get(c.tcid) === o).length,
        }])) as CycleMetrics['outcomes'],
        byPriority: byPriority.map((r) => ({ priority: `P${r.p}`, total: r.total, passing: r.passed, rate: r.total ? `${r.rate}%` : '—' })),
        acceptanceCriteria: { passing: acPassing, total: acRows.length },
        openDefects: openDefects.map((d) => ({ id: d.id, severity: d.severity ?? '?', tcid: d.tcid ?? 'untraced', trackerKey: d.trackerKey ?? '—', summary: d.summary ?? '' })),
        criteria,
        allMet,
        generatedBy: by,
        perStory: perStory.map(({ key, title, status, passing, total, failed, blocked, notRun }) => ({ key, title, status, passing, total, failed, blocked, notRun })),
        noPlan: noPlan.map((t) => t.key),
        notInRelease,
    };
    const failingCriteria = criteria.filter((c) => !c.met).map((c) => c.name);
    const passingCount = count('Passed') + count('Flaky');
    const summary =
        `${label}: ${cases.length} test cases, ${passingCount} passing, ${notExecuted} not executed, ` +
        `${openDefects.length} open defect(s); exit criteria ${allMet ? 'all met' : `NOT all met (${failingCriteria.join('; ')})`}`;

    const now = new Date();
    const releaseSet = [...new Set(plans.map((p) => p.release).filter((r): r is string => !!r))];
    const buildNow = process.env.BUILD_UNDER_TEST?.trim();
    const buildList = [...new Set([...builds, ...(buildNow ? [buildNow] : [])])];
    const title = scope.formal
        ? `QA test report — ${projectProfile.appName} — ${label}`
        : `Test cycle summary — ${projectProfile.appName} — ${label}`;

    if (scope.preview) {
        return { file: null, title, cases: cases.length, allMet, failingCriteria, summary, metrics };
    }

    // ---- write
    let commit = 'none yet — not a git repository';
    try { commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a repo */ }

    const stamp = now.toISOString().slice(0, 16).replace('T', ' ');
    const table = (head: string[], rows: (string | number)[][]) =>
        [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');

    // Named, never the host: BASE_URL is never written literally anywhere (PROJECT-PROFILE.md section 1).
    const environment = process.env.TEST_ENVIRONMENT?.trim() || 'not recorded — set `TEST_ENVIRONMENT` in `.env`';

    const md: string[] = [];
    md.push(`# ${title}`, '');
    // Only what a reader needs up front; the title already names the scope, and the audit details go last.
    // What identifies the report comes first, by its scope: the story, the stories, the epic, or the release.
    const releaseText = releaseSet.join(', ') || 'not in a release yet';
    const scopeRows: string[][] = scope.releases?.length
        ? [['Release', scope.releases.map((r) => (r === NO_RELEASE ? 'no release yet' : r)).join(', ')]]
        : scope.epics?.length
            ? [[scope.epics.length === 1 ? 'Epic' : 'Epics', scope.epics.join(', ')], ['Release', releaseText]]
            : scope.stories?.length
                ? [[plans.length === 1 ? 'Story' : 'Stories', plans.map((p) => p.storyKey).join(', ')], ['Release', releaseText]]
                : [['Release', releaseText]];
    md.push(table(['Field', 'Value'], [
        ...scopeRows,
        ['Build under test', buildList.join(', ') || 'not recorded — set `BUILD_UNDER_TEST` in `.env`'],
        ['Environment', environment],
        ['Browsers', [...browsers].join(', ') || '—'],
        ['Generated', `${by.name || 'name not recorded — set `QA_TESTER_NAME` in `.env`'} · ${stamp} UTC`],
    ]));
    md.push('');
    if (builds.size > 1) md.push(`> These results come from **${builds.size} different builds**. Re-run what was tested on an older build before closing.`, '');

    md.push('## Summary', '');
    md.push(`**${allMet ? 'Exit criteria all met' : 'Exit criteria NOT all met'}** — ${passingCount} of ${cases.length} test cases passing, ` +
        `${notExecuted} not executed, ${openDefects.length} open defect${openDefects.length === 1 ? '' : 's'}.` +
        `${failingCriteria.length ? ` Not met: ${failingCriteria.join('; ')}.` : ''}` +
        `${noPlan.length ? ` ${noPlan.length} ticket${noPlan.length === 1 ? '' : 's'} in scope ${noPlan.length === 1 ? 'has' : 'have'} no test plan yet: ${noPlan.map((n) => n.key).join(', ')}.` : ''}` +
        `${notInRelease.length ? ` Not in a release yet: ${notInRelease.join(', ')}.` : ''}` +
        ` This report states facts; whether to close the cycle is a person's decision.`, '');
    if (scope.notes?.trim()) md.push('## Notes', '', scope.notes.trim(), '');

    const automatedInput = inputs.includes(LATEST_RUN) ? LATEST_RUN : AUTOMATED_RECORD;
    const missing = [automatedInput, MANUAL_RECORD, DEFECT_DIR].filter((i) => !inputs.includes(i));
    if (missing.length) md.push(`> Inputs not found, treated as empty: ${missing.map((m) => `\`${m}\``).join(', ')}.`, '');

    md.push('## Tickets', '');
    md.push('_Each story in scope, with its status in Jira and how its test cases ended._', '');
    md.push(table(['Ticket', 'Title', 'Jira status', 'Release', 'Epic', 'Passing', 'Failed', 'Blocked', 'Not run', 'AC passing'],
        perStory.map((s) => [s.key, s.title, s.status, s.release, s.epic, `${s.passing}/${s.total}`, s.failed, s.blocked, s.notRun, s.ac])));
    md.push('');
    if (noPlan.length) {
        md.push('**In scope in Jira, but no test plan yet** — these tickets are not tested at all:', '');
        md.push(table(['Ticket', 'Title', 'Jira status'], noPlan.map((t) => [t.key, t.title ?? '—', t.status ?? '—'])), '');
    }
    if (notInRelease.length) md.push(`**Not in a release yet:** ${notInRelease.join(', ')} — no plan has a Release, so no release regression includes them.`, '');

    md.push('## Exit criteria', '');
    md.push(`_The conditions this project set for closing a test cycle (PROJECT-PROFILE.md section 10)._`, '');
    md.push(table(['Criterion', 'Threshold', 'Actual', 'Result'], criteria.map((c) => [c.name, c.threshold, c.actual, c.met ? 'Met' : '**Not met**'])), '');

    md.push('## Results', '');
    md.push(`_How every test case in scope ended — ${cases.length} active across ${plans.length} stor${plans.length === 1 ? 'y' : 'ies'}${retiredCount ? `, plus ${retiredCount} retired` : ''}._`, '');
    const outcomeRows = (['Passed', 'Flaky', 'Failed', 'Blocked', 'Skipped', 'Not Run'] as Outcome[]).map((o) => {
        const { automated: a, manual: m } = metrics.outcomes[o];
        return [o, a, m, a + m];
    });
    const sum = (k: 1 | 2 | 3) => outcomeRows.reduce((t, r) => t + (r[k] as number), 0);
    md.push(table(['Outcome', 'Automated', 'Manual', 'Total'], [...outcomeRows, ['**Total**', sum(1), sum(2), sum(3)]]), '');

    md.push('## By priority', '');
    md.push('_Priority 1 is what must work; priority 3 is lower-risk detail._', '');
    md.push(table(['Priority', 'Test cases', 'Passing', 'Rate'], byPriority.map((r) => [`P${r.p}`, r.total, r.passed, r.total ? `${r.rate}%` : '—'])), '');

    md.push('## Acceptance-criteria coverage', '');
    md.push('_Each acceptance criterion of each story. It passes only when every test case that verifies it passes._', '');
    md.push(acRows.length ? table(['Story', 'AC', 'Test cases', 'State'], acRows.map((r) => [r.story, r.ac, r.ids.join(', ') || '—', r.state === 'Passing' ? r.state : `**${r.state}**`])) : '_No traceability tables found in the plans._');
    md.push('');

    md.push('## Defects', '');
    if (defects.length === 0) md.push('_No defects recorded for this scope._');
    else {
        md.push('_Pending: confirmed, not yet filed. Raised: filed in the tracker, still open. Verified: fixed and passed on retest._', '');
        md.push(table(['Status', 'Count'], ['pending', 'raised', 'verified'].map((s) => [s, defects.filter((d) => d.status === s).length])), '');
        if (openDefects.length) {
            md.push('**Open defects:**', '');
            md.push(table(['Defect', 'Severity', 'Test case', 'Tracker', 'Summary'], openDefects.map((d) => [d.id, d.severity ?? '?', d.tcid ?? '**untraced**', d.trackerKey ?? '—', d.summary ?? ''])));
        }
    }
    md.push('');

    const failing = cases.filter((c) => ['Failed', 'Blocked', 'Not Run'].includes(outcomes.get(c.tcid)!));
    if (failing.length) {
        md.push('## Test cases not passing', '');
        md.push('_Every test case that failed, is blocked by a defect, or has not been run yet._', '');
        md.push(table(['TCID', 'Priority', 'Type', 'Outcome', 'Summary'], failing.map((c) => [c.tcid, c.priority ? `P${c.priority}` : '?', c.testType, outcomes.get(c.tcid)!, c.summary])), '');
    }

    md.push('## Traceability', '');
    md.push(`- Results with no TCID in their title: **${auto.untraced}**${auto.untraced ? ' — invisible to coverage above' : ''}`);
    md.push(`- Results whose TCID is in no plan: **${orphanResults.length}**${orphanResults.length ? ` — ${orphanResults.join(', ')}` : ''}`);
    md.push(`- Open defects with no TCID: **${openDefects.filter((d) => !d.tcid).length}**`, '');

    if (scope.formal) {
        md.push('## Sign-off', '');
        md.push(table(['Role', 'Name', 'Date', 'Decision'], [
            ['Prepared by', by.name || '—', now.toISOString().slice(0, 10), '—'],
            ['Reviewed by', ' ', ' ', ' '],
            ['Release decision', ' ', ' ', 'Close / Do not close'],
        ]), '');
    }

    const record = [
        `commit \`${commit}\``,
        `harness ${harnessVersion()}`,
        executedOn.length ? `automated results ${executedOn[0]} to ${executedOn[executedOn.length - 1]} UTC` : 'no automated results in scope',
        scope.since ? `results before ${scope.since} ignored` : null,
        by.name ? `name from ${by.source}` : null,
        scope.trigger ?? null,
    ].filter(Boolean).join(' · ');
    md.push('## How to read this report', '');
    md.push('- **Passed** — the test case did what its plan expects.');
    md.push('- **Flaky** — failed once, then passed on retry. It counts as passing, but is worth a look.');
    md.push('- **Failed** — the application did not do what the plan expects, or the test itself needs fixing.');
    md.push('- **Blocked** — set aside because of a known, open defect; it is run again once the defect is fixed.');
    md.push('- **Skipped** — deliberately not run in this selection.');
    md.push('- **Not run** — has not been executed yet: an automated case outside the run, or a manual case not yet done.');
    md.push('- **TCID** — the permanent ID of a test case, e.g. `PROJ-1234-TC002`: the story key, then the case number.', '');
    md.push(`_Record: ${record}._`, '');

    const fileStamp = now.toISOString().slice(0, 16).replace(/[:T]/g, '-');
    const outDir = path.join(ROOT, scope.formal ? 'specs/execution/reports' : scope.closure ? 'specs/execution/closure' : 'reports');
    fs.mkdirSync(outDir, { recursive: true });
    let out: string;
    if (scope.formal) {
        // One formal report per scope: a new one replaces the last, and git keeps the earlier versions. The date,
        // build and author are inside the report.
        out = path.join(outDir, `QA-Report_${namePart(projectProfile.appName)}_${namePart(scopeNamePart(scope, plans))}.md`);
    } else {
        // The after-run summaries are a running log: never overwrite one.
        const base = `cycle-summary-${slug(label)}-${fileStamp}`;
        out = path.join(outDir, `${base}.md`);
        for (let n = 2; fs.existsSync(out); n++) out = path.join(outDir, `${base}-${n}.md`);
    }
    fs.writeFileSync(out, md.join('\n'), 'utf8');

    return {
        file: path.relative(ROOT, out).split(path.sep).join('/'),
        title,
        cases: cases.length,
        allMet,
        failingCriteria,
        summary,
        metrics,
    };
}
