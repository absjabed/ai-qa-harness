/**
 * `npm run report:cycle` — the test report, by hand or from the reporter agent.
 *
 * The same report is also written automatically after every test run (lib/cycleReporter.ts) and at the end
 * of `npm run regression`. Use this to rebuild it — after recording manual results, say — or for a
 * different scope than the last run covered. `/playwright-test-reporter` drives it for a formal report.
 *
 * Scope (combine as needed; nothing = every story with a plan):
 *   --release 2.26                    stories in one client release (comma-separated or repeated; `none` = no release yet)
 *   --epics PROJ-100                  stories in these epics
 *   --stories PROJ-12,PROJ-15         chosen stories
 *   --since 2026-10-01                ignore results from before this cycle began
 *
 * Kind of report:
 *   (default)                         a cycle summary in reports/, not committed
 *   --closure                         the cycle's final summary, in specs/execution/closure/ — committed
 *   --formal                          a formal QA report: QA-Report_<app>_<scope>_<release>_<date-time>, a sign-off
 *                                     block, in specs/execution/reports/ — committed
 *   --format md,html,pdf              formats to write; Markdown is always written. Default: QA_REPORT_FORMAT, else md
 *   --by "<name>"                     who generated it, when QA_TESTER_NAME and the git user name are both missing
 *   --jira <file.json>                ticket titles and statuses fetched from Jira (see scripts/lib/cycle.ts JiraData)
 *   --notes <file.md>                 a written summary for the Notes section — never a source of numbers
 *   --strict                          exit non-zero if an exit criterion is unmet
 *
 * For the reporter agent:
 *   --list                            the releases, epics and stories there are to report on
 *   --defaults                        who reports would be generated by, and the default format
 *   --preview                         the report's numbers as JSON; writes nothing
 *
 * See scripts/lib/cycle.ts for what goes into it.
 */

import 'dotenv/config';
import fs from 'fs';
import path from 'path';
import { buildCycleReport, generatedBy, plansWithRelease, type JiraData } from './lib/cycle';
import { renderReport } from './lib/report-render';
import { NO_RELEASE, ROOT } from './lib/trace';

const args = process.argv.slice(2);
const values = (flag: string) =>
    args.flatMap((a, i) => (a === flag && args[i + 1] ? args[i + 1].split(',') : [])).map((s) => s.trim()).filter(Boolean);
const flag = (name: string) => args.includes(name);
const fail = (message: string): never => {
    console.error(`report:cycle — ${message}`);
    process.exit(1);
};

const FORMATS = ['md', 'html', 'pdf'];

function formats(): string[] {
    const asked = values('--format').map((f) => f.toLowerCase());
    const chosen = asked.length ? asked : (process.env.QA_REPORT_FORMAT ?? 'md').split(',').map((f) => f.trim().toLowerCase()).filter(Boolean);
    const unknown = chosen.filter((f) => !FORMATS.includes(f));
    if (unknown.length) fail(`unknown format ${unknown.join(', ')} — use md, html or pdf.`);
    return [...new Set(['md', ...chosen])];
}

function readFileArg(name: string): string | undefined {
    const file = values(name)[0];
    if (!file) return undefined;
    const full = path.resolve(ROOT, file);
    if (!fs.existsSync(full)) fail(`${name} ${file} — no such file.`);
    return fs.readFileSync(full, 'utf8');
}

async function main(): Promise<void> {
    if (flag('--list')) {
        const plans = plansWithRelease();
        const group = (key: (p: (typeof plans)[number]) => string | null) => {
            const out = new Map<string, string[]>();
            for (const p of plans) {
                const k = key(p);
                if (k) out.set(k, [...(out.get(k) ?? []), p.storyKey]);
            }
            return Object.fromEntries([...out].sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true })));
        };
        console.log(JSON.stringify({
            releases: group((p) => p.release ?? NO_RELEASE),
            epics: group((p) => p.epic),
            stories: plans.map((p) => ({ key: p.storyKey, title: p.title, release: p.release, epic: p.epic })),
        }, null, 2));
        return;
    }

    if (flag('--defaults')) {
        const by = generatedBy(values('--by')[0]);
        console.log(JSON.stringify({ generatedBy: by, defaultFormat: formats() }, null, 2));
        return;
    }

    const since = values('--since')[0];
    if (since && !/^\d{4}-\d{2}-\d{2}$/.test(since)) fail(`--since takes a date as YYYY-MM-DD, not "${since}".`);

    const jiraText = readFileArg('--jira');
    let jira: JiraData | undefined;
    if (jiraText) {
        try { jira = JSON.parse(jiraText) as JiraData; } catch { fail('--jira is not valid JSON.'); }
    }

    const formal = flag('--formal');
    const closure = flag('--closure');
    const result = buildCycleReport({
        releases: values('--release'),
        epics: values('--epics'),
        stories: values('--stories'),
        since,
        closure,
        formal,
        by: values('--by')[0],
        jira,
        notes: readFileArg('--notes'),
        preview: flag('--preview'),
        trigger: formal ? 'formal report' : closure ? 'closure report, run by hand' : 'run by hand',
    });

    if (flag('--preview')) {
        console.log(JSON.stringify({ title: result.title, summary: result.summary, ...result.metrics }, null, 2));
        return;
    }

    console.log(`report:cycle — ${result.summary}.`);
    if (!result.file) return;
    const written = [result.file];
    const extra = await renderReport(path.join(ROOT, result.file), result.title ?? 'Test report', formats(), result.metrics);
    written.push(...extra.map((f) => path.relative(ROOT, f).split(path.sep).join('/')));
    console.log(`Written to:\n${written.map((f) => `  ${f}`).join('\n')}`);
    process.exit(flag('--strict') && !result.allMet ? 1 : 0);
}

main().catch((error) => fail((error as Error).message));
